export const TranslationService = {
  /**
   * Obtenir une traduction
   */
  t(key: string, language: Language = 'fr'): string {
    return TRANSLATIONS[language]?.[key] || TRANSLATIONS['fr'][key] || key;
  },

  /**
   * Obtenir toutes les traductions pour une langue
   */
  getTranslations(language: Language): Record<string, string> {
    return TRANSLATIONS[language] || TRANSLATIONS['fr'];
  },

  /**
   * Vérifier si une clé existe
   */
  hasKey(key: string, language: Language = 'fr'): boolean {
    return key in (TRANSLATIONS[language] || TRANSLATIONS['fr']);
  },
};
